def render_solidity_project(
    contract_source: str,
    contract_name: str,
    invariants: list[Invariant],
    bounds: FuzzBounds,
    *,
    attack: bool | None = None,
    compromised_key: bool = False,
) -> dict[str, str]:
    """Render a complete Foundry project as {relative_path: content}.

    ``attack=None`` (default) follows ``bounds.attack_enabled`` — ON by
    default, so the pipeline gets the attacking simulator with no changes.
    Pass ``attack=False`` for the legacy plain harness (baselining), or
    ``attack=True`` to force the attack harness.

    ``compromised_key=True`` renders the compromised-key leg variant of
    the attack harness (Fix A): deployment stays neutral, but the handler
    impersonates the owner ON DEMAND (prank as the neutral deployer) so
    owner-gated invariants stay testable. Only meaningful with
    ``attack=True``.
    """
    use_attack = bounds.attack_enabled if attack is None else bool(attack)
    if use_attack:
        return _render_attack_project(
            contract_source, contract_name, invariants, bounds,
            compromised_key=compromised_key,
        )
    return _render_plain_project(contract_source, contract_name, invariants, bounds)


Renderer = Callable[[str, str, list[Invariant], FuzzBounds], dict[str, str]]

_RENDERERS: dict[str, Renderer] = {}


def register_renderer(language: str, renderer: Renderer) -> None:
    """Register a harness renderer for a language (Phase 6 extension point)."""
    _RENDERERS[language.lower()] = renderer


register_renderer("solidity", render_solidity_project)


def render_project(
    language: str,
    contract_source: str,
    contract_name: str,
    invariants: list[Invariant],
    bounds: FuzzBounds,
) -> dict[str, str]:
    """Render a fuzz project for ``language`` via its registered renderer."""
    renderer = _RENDERERS.get(language.lower())
    if renderer is None:
        raise ValueError(
            f"no invariant harness renderer for language {language!r} "
            f"(registered: {sorted(_RENDERERS)})"
        )
    return renderer(contract_source, contract_name, invariants, bounds)


def write_project(project_dir: Path, files: Mapping[str, str]) -> None:
    """Write a rendered project to disk."""
    for rel, content in files.items():
        dest = project_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content)
    LOGGER.info("wrote invariant harness project to %s (%d files)", project_dir, len(files))
