# ---------------------------------------------------------------------------
# Source introspection (regex-based; good enough for harness generation)
# ---------------------------------------------------------------------------

_CONTRACT_RE = re.compile(r"^\s*contract\s+(\w+)", re.MULTILINE)
_PRAGMA_RE = re.compile(r"^\s*pragma\s+solidity\s+([^;]+);", re.MULTILINE)
_FUNC_RE = re.compile(
    r"function\s+(\w+)\s*\(([^)]*)\)\s*"
    r"((?:external|public|internal|private)\s*)?"
    r"((?:payable|view|pure)\s*)?",
)


def extract_contract_name(source: str) -> str:
    """Return the first concrete contract name, defaulting to "Target"."""
    m = _CONTRACT_RE.search(source)
    return m.group(1) if m else "Target"


@dataclass
class ContractBlock:
    """One top-level contract/interface/library block with its body span."""

    name: str
    kind: str  # "contract" | "interface" | "library" | "abstract"
    start: int  # index of the opening brace
    end: int  # index just past the matching closing brace
    body: str  # source between the braces


_CONTRACT_DEF_RE = re.compile(
    r"\b(?:(abstract)\s+)?contract\s+(\w+)"
    r"|\binterface\s+(\w+)"
    r"|\blibrary\s+(\w+)"
)


def _code_mask(source: str) -> list[bool]:
    """Mark each character as code (True) vs comment/string (False)."""
    mask = [True] * len(source)
    i, n = 0, len(source)
    while i < n:
        c = source[i]
        nxt = source[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = source.find("\n", i)
            j = n if j == -1 else j
            for k in range(i, j):
                mask[k] = False
            i = j
        elif c == "/" and nxt == "*":
            j = source.find("*/", i + 2)
            j = n if j == -1 else j + 2
            for k in range(i, j):
                mask[k] = False
            i = j
        elif c in ("\"", "'"):
            j = i + 1
            while j < n:
                if source[j] == "\\":
                    j += 2
                    continue
                if source[j] == c:
                    j += 1
                    break
                j += 1
            for k in range(i, min(j, n)):
                mask[k] = False
            i = j
        else:
            i += 1
    return mask


def split_contracts(source: str) -> list[ContractBlock]:
    """Split source into top-level contract/interface/library blocks.

    Brace matching is comment/string-aware, so braces inside comments or
    string literals cannot corrupt the spans. Nested definitions are
    attributed to the outermost block.
    """
    mask = _code_mask(source)
    blocks: list[ContractBlock] = []
    for m in _CONTRACT_DEF_RE.finditer(source):
        if not mask[m.start()]:
            continue
        if m.group(2) is not None:
            name, kind = m.group(2), "abstract" if m.group(1) else "contract"
        elif m.group(3) is not None:
            name, kind = m.group(3), "interface"
        else:
            name, kind = m.group(4), "library"
        # find the opening brace after the match (skipping inheritance list)
        i = m.end()
        depth = 0
        open_idx = -1
        while i < len(source):
            if not mask[i]:
                i += 1
                continue
            if source[i] == "{":
                open_idx = i
                depth = 1
                i += 1
                break
            if source[i] == ";":
                break  # forward declaration / import-ish; no body
            i += 1
        if open_idx == -1:
            continue
        while i < len(source) and depth > 0:
            if mask[i]:
                if source[i] == "{":
                    depth += 1
                elif source[i] == "}":
                    depth -= 1
            i += 1
        if depth != 0:
            continue  # unbalanced; skip rather than misattribute
        blocks.append(ContractBlock(name, kind, open_idx, i, source[open_idx + 1:i - 1]))
    return blocks


def extract_contract_names(source: str) -> list[str]:
    """All top-level contract/interface/library names, in source order."""
    return [b.name for b in split_contracts(source)]


def extract_target_name(source: str) -> str:
    """The contract the harness deploys: first concrete contract.

    Falls back to the first block of any kind, then to "Target". (The
    legacy :func:`extract_contract_name` returns the first ``contract``
    keyword match, which may be an un-deployable stub; this is the
    deployability-aware version.)
    """
    blocks = split_contracts(source)
    for b in blocks:
        if b.kind == "contract":
            return b.name
    if blocks:
        return blocks[0].name
    return extract_contract_name(source)


def extract_target_functions(source: str) -> list[FunctionSig]:
    """Function signatures belonging to the deploy-target contract only.

    Weakness-hunt round, target 2: the harness used to wrap EVERY function
    in the file against the single deployed target, so any multi-contract
    file failed to compile (and died silently). Only the target's own
    functions are wrapped now; auxiliary contracts still compile as
    dependencies of the same source file.
    """
    blocks = split_contracts(source)
    target = extract_target_name(source)
    for b in blocks:
        if b.name == target:
            return extract_functions(b.body)
    return extract_functions(source)


def extract_pragma(source: str) -> str:
    """Return the source's pragma line, or a safe default."""
    m = _PRAGMA_RE.search(source)
    if m:
        return f"pragma solidity {m.group(1).strip()};"
    return "pragma solidity ^0.8.20;"


def extract_functions(source: str) -> list[FunctionSig]:
    """Parse top-level function signatures out of Solidity source."""
    sigs: list[FunctionSig] = []
    for m in _FUNC_RE.finditer(source):
        name = m.group(1)
        if name in ("constructor",):
            continue
        raw_params = m.group(2).strip()
        params: list[tuple[str, str]] = []
        if raw_params:
            for i, part in enumerate(raw_params.split(",")):
                tokens = part.strip().split()
                if not tokens:
                    continue
                ptype = tokens[0]
                # Weakness-hunt round, target 3: preserve `payable` in
                # `address payable` parameters. Dropping it produced
                # `target.sweep(p0)` with p0: address against
                # `sweep(address payable to)` — a compile failure.
                rest = tokens[1:]
                if "payable" in rest:
                    ptype += " payable"
                    rest = [t for t in rest if t != "payable"]
                pname = rest[0] if rest else f"p{i}"
                # strip data-location / calldata keywords leaking into the type
                ptype = ptype.replace("calldata", "").replace("memory", "").strip()
                params.append((ptype, re.sub(r"\W", "", pname) or f"p{i}"))
        mutability = (m.group(4) or "").strip()
        sigs.append(FunctionSig(name, params, mutability))
    return sigs


#: The harness deploys the target contract *as* this fixed neutral address
#: (via ``vm.prank`` in the handler constructor), so the harness itself is
#: never the contract's owner. Owner-gated paths stay unreachable to the
#: fuzzer (no owner-confusion false positives), while tx.origin phishing
#: remains testable (see ``act_phishOrigin``). Checksum verified against
#: the pinned Foundry build; also excluded from mined-sender extraction so
#: the fuzzer can never accidentally act as the owner.
NEUTRAL_DEPLOYER = "0x00000000000000000000000000000000DeaDBeef"

#: Cheat-code address: never mined as a sender.
_VM_ADDRESS = "0x7109709ecfa91a80626ff3989d68f67f5b1dd12d"

_MINED_ADDR_RE = re.compile(r"0x[0-9a-fA-F]{40}")


def extract_mined_senders(source: str, limit: int = 8) -> list[str]:
    """Mine hardcoded address literals from the source as candidate senders.

    Restores the old fuzzer's address-mining: a role gated on a hardcoded
    address (e.g. ``pauser = address(0x...dEaD)``) is unreachable to a
    fuzzer that only ever calls as itself. Every distinct non-zero literal
    becomes a sender the harness can impersonate via prank.
    """
    seen: list[str] = []
    for m in _MINED_ADDR_RE.finditer(source):
        addr = m.group(0).lower()
        if addr == "0x" + "0" * 40:
            continue
        if addr in (_VM_ADDRESS, NEUTRAL_DEPLOYER.lower()):
            continue
        if addr not in seen:
            seen.append(addr)
        if len(seen) >= limit:
            break
    return seen


def addr_expr(hex_addr: str) -> str:
    """Render a hex address as Solidity that never trips checksum validation.

    solc ≥0.8.18 rejects 40-hex-char literals with a bad EIP-55 checksum —
    and we cannot compute EIP-55 here (no keccak dependency) — so mined
    addresses render as ``address(uint160(<decimal>))``, which the
    compiler always accepts.
    """
    return f"address(uint160({int(hex_addr, 16)}))"


# ---------------------------------------------------------------------------
# Compromised-key analysis (Fix A: weakness 1's overcorrection)
# ---------------------------------------------------------------------------
# The neutral-deployer fix made the harness unable to act as the owner at
# all — so owner-gated functions became untestable and 8 "compromised owner
# key" batch cases regressed. The compromised-key leg impersonates the
# owner ON DEMAND (prank as the neutral deployer) in a separate bounded
# campaign; these helpers decide when that leg applies and which rules it
# may assert.

#: Modifiers that conventionally gate a function on the owner key
#: (matched case-insensitively against the function's header).
_OWNER_MODIFIERS = frozenset({
    "onlyowner",
    "onlyadmin",
    "onlyadministrator",
    "onlygovernor",
    "onlypauser",
    "onlyminter",
    "onlyauthority",
    "onlymanager",
    "onlyoperator",
    "onlyguardian",
    "onlysuperadmin",
})

_CONSTRUCTOR_RE = re.compile(r"\bconstructor\s*\([^)]*\)[^{;]*\{")
_INITIALIZER_RE = re.compile(
    r"\bfunction\s+(?:initialize|init|setup)\s*\([^)]*\)[^{;]*\{"
)
#: `<name> = msg.sender` — the deployer-key assignment (constructor or
#: proxy-style initializer).
_SENDER_ASSIGN_RE = re.compile(r"\b([A-Za-z_]\w*)\s*=\s*msg\.sender\b")
#: `require(msg.sender == <role>)` / `assert(msg.sender == <role>)`
#: (and the reversed `<role> == msg.sender` form).
_SENDER_CHECK_RES = (
    re.compile(r"\b(?:require|assert)\s*\(\s*msg\.sender\s*==\s*([A-Za-z_]\w*)"),
    re.compile(r"\b(?:require|assert)\s*\(\s*([A-Za-z_]\w*)\s*==\s*msg\.sender"),
    re.compile(
        r"\bif\s*\(\s*msg\.sender\s*!=\s*([A-Za-z_]\w*)\s*\)\s*revert\b"
    ),
    re.compile(
        r"\bif\s*\(\s*([A-Za-z_]\w*)\s*!=\s*msg\.sender\s*\)\s*revert\b"
    ),
)


def _brace_span(text: str, open_idx: int, mask: list[bool]) -> tuple[int, int]:
    """Return (body_start, body_end) for the brace at ``open_idx``.

    ``body_end`` is the index just past the matching close brace;
    ``(-1, -1)`` when unbalanced.
    """
    depth = 0
    i = open_idx
    n = len(text)
    while i < n:
        if mask[i]:
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    return open_idx + 1, i
        i += 1
    return -1, -1


def _iter_function_spans(
    body: str,
) -> list[tuple[str, str, str]]:
    """Yield (name, header, fn_body) for each function defined in ``body``.

    Comment/string-aware: braces inside comments or literals cannot corrupt
    the spans. ``header`` runs from the ``function`` keyword to the opening
    brace (so modifiers like ``onlyOwner`` are visible); ``fn_body`` is the
    code between the braces.
    """
    mask = _code_mask(body)
    spans: list[tuple[str, str, str]] = []
    for m in _FUNC_RE.finditer(body):
        if not mask[m.start()]:
            continue
        i = m.end()
        n = len(body)
        while i < n:
            if mask[i]:
                if body[i] == "{":
                    break
                if body[i] == ";":
                    break  # declaration without a body (interface/abstract)
            i += 1
        if i >= n or body[i] != "{":
            continue
        start, end = _brace_span(body, i, mask)
        if start == -1:
            continue
        spans.append((m.group(1), body[m.start():i], body[start:end]))
    return spans


def _owner_roles_in(body: str) -> set[str]:
    """State-variable names that hold the deployer/owner key.

    A role qualifies when the constructor (or a proxy-style
    ``initialize``/``init``/``setup`` function) assigns it ``msg.sender`` —
    the precise "the deployer is this role" signal, not a name guess.
    """
    roles: set[str] = set()
    mask = _code_mask(body)
    for pattern in (_CONSTRUCTOR_RE, _INITIALIZER_RE):
        for m in pattern.finditer(body):
            if not mask[m.start()]:
                continue
            start, end = _brace_span(body, m.end() - 1, mask)
            if start == -1:
                continue
            ctor_body = body[start:end]
            for am in _SENDER_ASSIGN_RE.finditer(ctor_body):
                roles.add(am.group(1))
    return roles


def detect_owner_gated_functions(
    source: str,
    functions: list[FunctionSig] | None = None,
) -> list[FunctionSig]:
    """Return the state-changing functions gated on the deployer/owner key.

    A function counts as owner-gated when it is state-changing and either

    - its header carries an owner-style modifier (``onlyOwner`` and kin), or
    - its body checks ``msg.sender`` against a role the constructor (or a
      proxy-style initializer) assigned ``msg.sender`` — i.e. the role the
      neutral deployer impersonates in the compromised-key leg.

    Deliberately NOT matched: ``tx.origin`` gates (those belong to the
    phishing threat model, tested in the neutral leg) and gates on
    hardcoded non-deployer addresses (covered by sender mining).
    """
    sigs = functions if functions is not None else extract_target_functions(source)
    target_body = source
    target = extract_target_name(source)
    for b in split_contracts(source):
        if b.name == target:
            target_body = b.body
            break
    roles = _owner_roles_in(target_body)
    spans = {name: (header, fbody) for name, header, fbody in _iter_function_spans(target_body)}
    gated: list[FunctionSig] = []
    for sig in sigs:
        if not sig.state_changing:
            continue
        span = spans.get(sig.name)
        if span is None:
            continue
        header, fbody = span
        if _header_has_owner_modifier(header):
            gated.append(sig)
            continue
        for rx in _SENDER_CHECK_RES:
            hit = False
            for m in rx.finditer(fbody):
                if m.group(1) in roles:
                    gated.append(sig)
                    hit = True
                    break
            if hit:
                break
    return gated


def _header_has_owner_modifier(header: str) -> bool:
    """True when the function header names an owner-style modifier."""
    for m in re.finditer(r"\b([A-Za-z_]\w*)\b", header):
        if m.group(1).lower() in _OWNER_MODIFIERS:
            return True
    return False


#: Invariant assertions that reference an owner-identity view
#: (``owner()``, ``deployer()``, ``admin()``, ...). Such rules encode the
#: benign-owner assumption — "this only changes via the trusted role" —
#: which is vacuous once the owner key itself is the attacker, so the
#: compromised-key leg must not assert them.
_OWNER_IDENTITY_CALL_RE = re.compile(
    r"\.\s*(owner|deployer|admin|administrator|governor|pauser|minter|"
    r"authority|manager|operator|guardian|superadmin)\s*\(",
    re.IGNORECASE,
)

#: Invariant assertions of the "never changes" shape:
#: ``target.<view>(...) == <literal>`` (or ``!=``). These encode "this
#: state never moves from its constant value" — again a benign-owner
#: assumption: a compromised owner legitimately exercising an owner-gated
#: setter would break them, manufacturing a false positive.
_CONSTANT_EQ_RE = re.compile(
    r"target\.\s*[A-Za-z_]\w*\s*\([^)]*\)\s*(?:==|!=)\s*"
    r"(?:false|true|0x0+|0+|[0-9][0-9_]*(?:\.[0-9]+)?(?:[eE][0-9]+)?"
    r"|address\s*\(\s*0\s*\))\b",
    re.IGNORECASE,
)


def split_compromised_key_invariants(
    invariants: list[Invariant],
) -> tuple[list[Invariant], list[tuple[str, str]]]:
    """Split invariants into (eligible, [(id, reason), ...] excluded).

    The compromised-key leg may only assert invariants that still make
    sense when the owner is adversarial — consequence bounds like "price
    can't jump >10%" or "fee can't exceed the cap". Excluded:

    - rules referencing owner-identity views (``owner()``, ``deployer()``,
      ...): "ownership never changes without the owner" is vacuous when
      the owner key is compromised (batch_01 ``n5-owner-clean``);
    - "never changes" equalities (``target.paused() == false``): a
      compromised owner legitimately pausing would break them
      (batch_01 ``n7-pausable-clean``).

    Without this split the leg would reintroduce exactly the
    owner-confusion false alarms the neutral-deployer fix removed.
    """
    eligible: list[Invariant] = []
    excluded: list[tuple[str, str]] = []
    for inv in invariants:
        assertion = inv.assertion or ""
        if _OWNER_IDENTITY_CALL_RE.search(assertion):
            excluded.append(
                (inv.id, "references an owner-identity view (benign-owner assumption)")
            )
            continue
        if _CONSTANT_EQ_RE.search(" ".join(assertion.split())):
            excluded.append(
                (inv.id, "'never changes' equality (benign-owner assumption)")
            )
            continue
        eligible.append(inv)
    return eligible, excluded


def sender_pool(
    source: str, bounds: FuzzBounds, *, extra: list[str] | None = None,
) -> list[str]:
    """Ordered sender pool: built-ins, config, mined-from-source, extra.

    ``extra`` (e.g. attacker-contract placeholders) is appended last; the
    handler always seeds slot 0 with itself, so the pool is never empty.
    """
    pool = [
        "address(uint160(0xB0B))",
        "address(uint160(0xC0C))",
        "address(uint160(0xD0D))",
    ]
    for addr in list(bounds.impersonate_senders) + extract_mined_senders(source):
        expr = addr_expr(addr)
        if expr not in pool:
            pool.append(expr)
    for addr in extra or []:
        if addr not in pool:
            pool.append(addr)
    return pool


def _generic_arg_expr(ptype: str, index: int, addr_expr: str = "u") -> str:
    """A deterministic generic argument expression for one parameter type.

    Used by the entry dispatcher (phishing + coverage): argument quality
    does not matter there — the fuzzer's own calls provide variety — so
    every parameter maps to a cheap deterministic expression over the
    dispatcher seeds (``a``/``b``) and an address expression.
    """
    if ptype.startswith("uint"):
        return "a" if index % 2 == 0 else "b"
    if ptype.startswith("int"):
        return f"int256({'a' if index % 2 == 0 else 'b'})"
    if ptype == "bool":
        return "true" if index % 2 == 0 else "false"
    if ptype == "address":
        return addr_expr
    if ptype == "address payable":
        return f"payable({addr_expr})"
    if ptype.startswith("bytes"):
        return f"{ptype}(a)"
    return "a"


#: Weakness-hunt round, target 6: suspicious name fragments, checked
#: first by the deterministic coverage sweep (seed-1337 dilution fix).
_SUSPICIOUS_FN_RE = re.compile(
    r"skim|mint|drain|withdraw|sweep|claim|steal|loot|pillage|"
    r"extract|rescue|recover|emergency|backdoor|selfdestruct|"
    r"suicide|kill|destroy|pause|unpause|upgrade|setOwner|"
    r"transferOwnership|renounce",
    re.IGNORECASE,
)


def coverage_order(
    sigs: list[FunctionSig], invariants: list[Invariant]
) -> list[FunctionSig]:
    """Order entry points suspicious-first for the coverage sweep.

    Functions referenced by invariants and functions with suspicious
    names (skim/mint/drain/...) come first; state-changing before view;
    alphabetical as the final tiebreak (deterministic). The sweep visits
    every entry point regardless — the order only decides what gets hit
    first when the budget is tight.
    """
    inv_fns: set[str] = set()
    for inv in invariants:
        inv_fns.update(inv.functions)
        inv_fns.update(re.findall(r"target\.(\w+)\s*\(", inv.assertion))
        inv_fns.update(re.findall(r"target\.(\w+)\s*\(", inv.statement))
    def key(sig: FunctionSig) -> tuple[int, int, str]:
        s = 0
        if sig.name in inv_fns:
            s += 100
        if _SUSPICIOUS_FN_RE.search(sig.name):
            s += 50
        changing = 1 if sig.mutability in ("nonpayable", "payable") else 0
        return (-s, -changing, sig.name)
    return sorted(sigs, key=key)


def _render_entry_dispatcher(
    contract_name: str,
    entries: list[FunctionSig],
    *,
    via_passthrough: bool,
    chunk_size: int = 256,
) -> str:
    """Render ``_wgCallEntry``: call the k-th target entry point.

    One dispatcher serves the phishing action (target 1: tx.origin with
    ``msg.sender != tx.origin``) and — from the weakness-hunt round's
    target 6 — the deterministic coverage sweep. Every leaf swallows
    reverts: the goal is to *attempt* the call, never to require success.

    ``via_passthrough=True`` (ghost mode) routes through the handler's own
    passthroughs so ghost accounting stays in lockstep; ``False`` (attack
    mode) calls the target directly inside try/catch.
    """
    n = len(entries)
    addr_expr = "_wgPickSender(a)" if via_passthrough else "u"
    chunks: list[str] = []
    for ci in range(0, n, chunk_size):
        chunk = entries[ci:ci + chunk_size]
        lines = [
            f"    function _wgEntryChunk{ci // chunk_size}"
            "(uint256 idx, address u, uint256 a, uint256 b, uint256 s) internal {"
        ]
        for j, fn in enumerate(chunk):
            k = ci + j
            args = ", ".join(
                _generic_arg_expr(t, i, addr_expr)
                for i, (t, _) in enumerate(fn.params)
            )
            if via_passthrough:
                args = ", ".join(([args] if args else []) + ["s"])
                call = f"this.{fn.name}({args})"
                if fn.mutability == "payable":
                    call = f"this.{fn.name}{{value: 0}}({args})"
            else:
                call = f"target.{fn.name}({args})"
                if fn.mutability == "payable":
                    call = f"target.{fn.name}{{value: 0}}({args})"
            lines.append(f"        if (idx == {k}) {{ try {call} {{}} catch {{}} return; }}")
        lines.append("    }")
        chunks.append("\n".join(lines))
    dispatch = [
        "    // Call the k-th target entry point (mod entry count).",
        "    // Shared by the phishing action and the coverage sweep.",
        f"    uint256 constant WG_ENTRY_COUNT = {n};",
        "    function _wgCallEntry(uint256 k, address u, uint256 a, uint256 b, uint256 s) internal {",
        "        if (WG_ENTRY_COUNT == 0) return;",
        "        uint256 idx = k % WG_ENTRY_COUNT;",
    ]
    for ci in range(0, n, chunk_size):
        dispatch.append(
            f"        if (idx < {ci + chunk_size}) {{ _wgEntryChunk{ci // chunk_size}(idx, u, a, b, s); return; }}"
        )
    dispatch.append("    }")
    return "\n".join(dispatch + [""] + chunks)


